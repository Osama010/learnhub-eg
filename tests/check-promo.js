const fs = require("fs");
const src = fs.readFileSync(__dirname + "/../src/domain/promo.js", "utf8").replace(/export /g, "");
const m = new Function(src + "; return {normalizeCode,validatePromo,promoStatus,trialSubData,promoLabel};")();
let f = 0; const ok = (c, n) => { if (!c) { f++; console.log("FAIL", n); } };
ok(m.normalizeCode(" ab c-12_x! ") === "ABC-12_X", "normalize");
ok(m.normalizeCode("ا".repeat(5)) === "" && m.normalizeCode("A".repeat(30)).length === 20, "normalize limits");
ok(m.validatePromo({ code: "ab" , kind: "trial", value: 5 }).error, "short code");
ok(m.validatePromo({ code: "abc", kind: "trial", value: 0 }).error && m.validatePromo({ code: "abc", kind: "trial", value: 91 }).error, "trial range");
ok(m.validatePromo({ code: "abc", kind: "discount", value: 101 }).error, "discount range");
const t = m.validatePromo({ code: "wel14", kind: "trial", value: 14, maxUses: "5", expiresAt: "2027-01-01" }).doc;
ok(t.code === "WEL14" && t.trialDays === 14 && t.maxUses === 5 && !("discountPct" in t), "trial doc");
const d = m.validatePromo({ code: "off", kind: "discount", value: 20 }).doc;
ok(d.discountPct === 20 && d.maxUses === 0 && !("trialDays" in d), "discount doc");
ok(m.validatePromo({ code: "abc", kind: "trial", value: 3, expiresAt: "x" }).error, "bad date");
const now = new Date("2026-11-27T10:00:00").getTime();
ok(m.promoStatus(null, now).ok === false, "missing");
ok(m.promoStatus({ active: false }, now).ok === false, "inactive");
ok(m.promoStatus({ expiresAt: "2026-11-26" }, now).ok === false && m.promoStatus({ expiresAt: "2026-11-27" }, now).ok, "expiry inclusive");
ok(m.promoStatus({ maxUses: 2, uses: 2 }, now).ok === false && m.promoStatus({ maxUses: 0, uses: 99 }, now).ok, "max uses");
const s = m.trialSubData({ trialDays: 14 }, "2026-11-27");
ok(s.subType === "monthly" && s.subAmount === 0 && s.subStart === "2026-11-27" && s.subEnd === "2026-12-10", "trial sub " + s.subEnd);
ok(m.trialSubData({ trialDays: 1 }, "2026-11-27").subEnd === "2026-11-27", "1 day");
ok(m.promoLabel(t) === "تجربة 14 يوم" && m.promoLabel(d) === "خصم 20%", "label");
console.log(f ? "promo: " + f + " FAIL" : "promo: all pass"); process.exit(f ? 1 : 0);
