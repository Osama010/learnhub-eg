(async () => {
  let f = 0; const ok = (c, n) => { if (!c) { f++; console.log("FAIL", n); } };
  const S = await import(__dirname + "/../src/domain/srs.js");
  const DAY = 86400000, t0 = Date.UTC(2026, 10, 20);
  const T = (ms) => ({ seconds: ms / 1000 });
  const quiz = { id: "q1", title: "ك1", lessonId: "l1", teacherId: "t", questions: [{ q: "a" }, { q: "b" }, { q: "c" }] };
  const exam = { id: "e1", title: "ام1", quiz: [{ q: "x" }] };
  const att = [{ quizId: "q1", updatedAt: T(t0), answers: [{ correct: false }, { correct: true }, { correct: false }] }, { examId: "e1", updatedAt: T(t0 + DAY), answers: [{ correct: false }] }, { quizId: "gone", answers: [{ correct: false }] }];
  const items = S.srsItems({ attempts: att, quizzes: [quiz], exams: [exam] });
  ok(items.length === 3 && items.map((i) => i.key).join() === "qq1:0,qq1:2,xe1:0", "items from wrong answers only " + items.map((i) => i.key));
  ok(items[0].wrongAt === t0 && items[0].lessonId === "l1", "wrongAt + lesson");
  let sc = S.srsSchedule(items, {}, t0 + DAY);
  ok(sc.length === 3 && S.dueItems(sc).length === 0, "nothing due before 2 days");
  sc = S.srsSchedule(items, {}, t0 + 2 * DAY);
  ok(S.dueItems(sc).length === 2 && sc[0].isDue, "two quiz questions due at 2 days; exam one a day later");
  let st = S.srsAnswer({}, items[0], true, t0 + 2 * DAY);
  ok(st["qq1:0"].step === 1 && st["qq1:0"].due === t0 + 9 * DAY, "knew: back after 7 days");
  sc = S.srsSchedule(items, st, t0 + 5 * DAY); ok(!sc.find((x) => x.key === "qq1:0").isDue, "not due during the week");
  sc = S.srsSchedule(items, st, t0 + 9 * DAY); ok(sc.find((x) => x.key === "qq1:0").isDue, "due after a week");
  st = S.srsAnswer(st, items[0], true, t0 + 9 * DAY);
  ok(S.srsSchedule(items, st, t0 + 30 * DAY).every((x) => x.key !== "qq1:0"), "second success graduates it");
  st = S.srsAnswer({}, items[1], false, t0 + 3 * DAY);
  ok(st["qq1:2"].step === 0 && st["qq1:2"].due === t0 + 5 * DAY, "didn't know: back in 2 days");
  st = S.srsAnswer({}, items[0], true, t0 + 2 * DAY);
  const re = items.map((i) => i.key === "qq1:0" ? { ...i, wrongAt: t0 + 10 * DAY } : i);
  ok(S.srsSchedule(re, st, t0 + 11 * DAY).find((x) => x.key === "qq1:0").step === 0, "new wrong attempt resets the schedule");
  ok(Object.keys(S.srsPrune(st, items.slice(1))).length === 0 && Object.keys(S.srsPrune(st, items)).length === 1, "prune solved");
  // exam night
  const weak = [{ level: "weak", lessonId: "l1", label: "الدرس 1", pct: 30 }, { level: "mid", lessonId: "l2", label: "ب", pct: 60 }, { level: "weak", lessonId: "lx", label: "مش موجود", pct: 10 }];
  const lessons = [{ id: "l1", teacherId: "t" }, { id: "l2", teacherId: "t" }];
  const bigItems = Array.from({ length: 30 }, (_, i) => ({ key: "k" + i, itemId: "q1", isExam: false, idx: i }));
  const p = S.examNightPlan({ budgetMin: 60, items: bigItems, weak, quizzes: [quiz], attempts: [{ quizId: "q1", score: 1, total: 3 }], lessons });
  ok(p.budget === 60 && p.usedMin <= 60 && p.usedMin > 0, "within budget " + p.usedMin);
  ok(p.blocks[0].kind === "lesson" && p.blocks[0].href === "#/student/lesson/l1" && p.blocks.every((b) => b.href), "weak lesson first, only existing lessons");
  ok(!p.blocks.some((b) => b.title === "مش موجود" || b.title === "ب"), "no unknown/mid topics");
  ok(p.blocks.some((b) => b.kind === "flash") && p.blocks.some((b) => b.kind === "quiz"), "flashcards and failed quiz");
  ok(p.blocks.every((b, i) => b.from === (i ? p.blocks[i - 1].to : 0) && b.to - b.from === b.minutes), "contiguous timeline");
  const tiny = S.examNightPlan({ budgetMin: 5, items: bigItems, weak, quizzes: [quiz], attempts: [], lessons });
  ok(tiny.budget === 15 && tiny.usedMin <= 15, "min budget 15");
  ok(S.examNightPlan({ budgetMin: 60, items: [], weak: [], quizzes: [], attempts: [], lessons: [] }).blocks.length === 0, "nothing weak = empty plan");
  const other = S.examNightPlan({ budgetMin: 60, items: bigItems, weak, quizzes: [quiz], attempts: [], lessons, teacherId: "other" });
  ok(!other.blocks.some((b) => b.kind === "lesson" || b.kind === "quiz"), "teacher filter");
  console.log(f ? "srs: " + f + " FAIL" : "srs: all pass"); process.exit(f ? 1 : 0);
})();
