/** role: الدور اللي اتحسب للحساب بعد الدخول. blockedStatus: حالة الطالب لو role === "blocked". */
export function roleMismatchMessage({ expectedRole, role, blockedStatus, relinkStage, portal }) {
  if (expectedRole === "student") {
    if (role === "blocked") {
      return blockedStatus === "rejected" ? "طلبك اترفض، كلّم مدرسك."
        : blockedStatus === "suspended" ? "حسابك متوقف مؤقتًا، كلّم مدرسك أو إدارة المنصة."
        : "طلبك لسه تحت المراجعة، استنى موافقة مدرسك.";
    }
    if (role === "unknown") return "حسابك موجود بس ملف الطالب مش متربط بيه. جرّب تاني بعد شوية، ولو المشكلة فضلت ابعتلنا الكود ده: " + (relinkStage || "R?");
    return portal ? "الحساب ده مش حساب طالب. لو انت مدرس ادخل من رابط المدرسين." : "الحساب ده مش حساب طالب. لو انت مدرس اختار كارت مدرس.";
  }
  if (expectedRole === "teacher") {
    return role === "teacherSuspended" ? "حسابك متوقف مؤقتًا من إدارة المنصة. كلّم إدارة المنصة."
      : role === "teacherSubExpired" ? "اشتراكك في المنصة انتهى، كلّم إدارة المنصة للتجديد."
      : "الحساب ده مش حساب مدرس.";
  }
  return "الحساب ده مش مسجل كمشرف. لو انت أدمن جديد، ادخل الأول بجوجل واربط باسورد من تاب المشرفين.";
}

